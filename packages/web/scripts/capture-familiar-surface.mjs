// Issue #156: real static-demo interactions, with no API or external traffic.
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { navigate } from './app-navigation.mjs';
const { chromium } = createRequire(resolve(process.env.OPENSIGHT_SCREENSHOT_TOOLS ?? '/home/hatch/workspace/tools/screenshots', 'package.json'))('playwright-core');
const out = resolve(process.env.OPENSIGHT_SCREENSHOT_OUTPUT ?? '.opensight/issue-156/browser');
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.OPENSIGHT_CHROMIUM ?? '/opt/meta-chromium/chrome', args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
page.setDefaultTimeout(15000);
const errors = [], external = [];
page.on('pageerror', error => errors.push(error.message));
await page.route(/^https?:/, route => { external.push(route.request().url()); return route.abort(); });
const button = name => page.getByRole('button', { name, exact: true });
const capture = async name => { await page.mouse.move(5, 5); await page.evaluate(() => window.scrollTo(0, 0)); await page.screenshot({ path: resolve(out, `${name}.png`), fullPage: true }); };
try {
  await page.goto(`${new URL('../dist/opensight-demo.html', import.meta.url).href}#/analyses/new`);
  await page.getByRole('radio', { name: 'Sample sales data' }).check();
  const search = page.getByRole('combobox', { name: 'Explore fields (optional)' });
  await search.fill('revenu');
  assert.equal(await button('Create analysis').isDisabled(), true);
  assert.match(await page.locator('.field-search [role=alert]').innerText(), /Unknown field.*revenu/);
  await search.press('Enter'); assert.equal(await search.inputValue(), '[revenue]');
  await button('Add by dimension').click();
  await search.fill('[revenue] by reg'); await search.press('Enter');
  assert.equal(await search.inputValue(), '[revenue] by [region]');
  await capture('create-analysis');
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await capture('search-mobile');
  await button('Create analysis').click();
  await page.locator('.author-card .chart svg').waitFor();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await button('Save draft').click(); await page.reload();
  await page.locator('.author-card .chart svg').waitFor();
  await capture('search-result');
  await navigate(page, 'data-prep'); await button('New').click();
  await page.getByLabel('Dataset name', { exact: true }).fill('Regional sales preparation');
  await page.getByRole('tab', { name: 'Preview', exact: true }).click();
  await button('＋ Formula column').click();
  await page.getByLabel('Column name', { exact: true }).fill('net_revenue');
  await page.getByLabel('Expression', { exact: true }).fill('{missing} * 0.9');
  assert.equal(await button('Apply step').isDisabled(), true);
  await page.getByLabel('Expression', { exact: true }).fill('{revenue} * 0.9');
  await button('Apply step').click();
  await button('Filter net_revenue').click();
  await page.getByLabel('Operator', { exact: true }).selectOption('GREATER_THAN_OR_EQUAL_TO');
  await page.getByLabel('Value', { exact: true }).fill('100'); await button('Apply step').click();
  await button('Rename region').click();
  await page.getByLabel('New name', { exact: true }).fill('area'); await button('Apply step').click();
  assert.equal(await page.getByRole('tab', { name: 'Preview', exact: true }).getAttribute('aria-selected'), 'true');
  assert.match(await page.locator('.prep-preview').innerText(), /Live preview is unavailable in the static demo/);
  assert.equal(await page.locator('.prep-preview tbody tr').count(), 0);
  assert.equal(await button('Save pipeline').isDisabled(), true);
  await capture('data-prep');
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await capture('grid-mobile');
  assert.deepEqual(errors, []); assert.deepEqual(external, []);
  const report = { passed: true, errors, external, viewports: [1440, 390], grid: ['calculate', 'filter', 'rename'], search: 'bar saved/reloaded, keyboard selection, unknown token rejected' };
  await writeFile(resolve(out, 'verification.json'), JSON.stringify(report, null, 2)); console.log(JSON.stringify(report));
} catch (error) { await capture('failure'); throw error; }
finally { await browser.close(); }
