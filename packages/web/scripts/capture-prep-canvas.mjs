// Issue #58: exercise the rebuilt offline demo and capture synthetic prep flows.
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { navigate } from './app-navigation.mjs';
const { chromium } = createRequire(resolve(process.env.OPENSIGHT_SCREENSHOT_TOOLS ?? '/home/hatch/workspace/tools/screenshots', 'package.json'))('playwright-core');
const out = resolve(process.env.OPENSIGHT_SCREENSHOT_OUTPUT ?? '.opensight/issue-58/browser');
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.OPENSIGHT_CHROMIUM ?? '/opt/meta-chromium/chrome', args: ['--no-sandbox', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, reducedMotion: 'reduce' });
page.setDefaultTimeout(10000);
const errors = [], external = [], geometry = [];
page.on('pageerror', error => errors.push(error.message));
await page.route(/^https?:/, route => { external.push(route.request().url()); return route.abort(); });
const button = name => page.getByRole('button', { name, exact: true });
const configure = () => page.getByRole('tab', { name: 'Configure', exact: true });
const preview = () => page.getByRole('tab', { name: 'Preview', exact: true });
const capture = async name => { await page.mouse.move(1400, 5); await page.evaluate(() => window.scrollTo(0, 0)); await page.screenshot({ path: resolve(out, `${name}.png`), fullPage: true }); };
try {
  await page.goto(new URL('../dist/opensight-demo.html', import.meta.url).href, { waitUntil: 'networkidle' });
  await navigate(page, 'data-prep');
  await button('New').click();
  await page.getByLabel('Dataset name', { exact: true }).fill('Regional sales preparation');
  assert.deepEqual(await page.locator('.prep-sidebar h3').allTextContents(), ['Input', 'Column transformations', 'Combine transformations', 'Other']);
  await button('＋ Add data').click();
  await page.getByLabel('Stage a source', { exact: true }).selectOption(JSON.stringify('demo-regions'));
  await button('Stage input').click();
  await page.locator('.prep-node.staged').waitFor();
  await button('＋ Change data type').click();
  await page.getByLabel('Column', { exact: true }).selectOption('revenue');
  await page.getByLabel('New type', { exact: true }).selectOption('INTEGER');
  await preview().click();
  assert.equal(await page.locator('.prep-step-editor').isVisible(), false);
  await preview().press('ArrowLeft');
  assert.equal(await configure().getAttribute('aria-selected'), 'true');
  assert.equal(await page.getByLabel('New type', { exact: true }).inputValue(), 'INTEGER');
  await button('Apply step').click();
  await button('＋ Join').click();
  await page.getByLabel('Step name (optional)', { exact: true }).fill('Regional sales');
  assert.equal(await page.getByRole('radio', { name: 'Left join', exact: true }).getAttribute('aria-checked'), 'true');
  await page.getByRole('radio', { name: 'Left join', exact: true }).press('ArrowRight');
  assert.equal(await page.getByRole('radio', { name: 'Inner join', exact: true }).getAttribute('aria-checked'), 'true');
  await page.getByRole('radio', { name: 'Inner join', exact: true }).press('End');
  assert.equal(await page.getByRole('radio', { name: 'Full join', exact: true }).getAttribute('aria-checked'), 'true');
  await page.getByRole('radio', { name: 'Full join', exact: true }).press('Home');
  await page.getByLabel('Left column 2', { exact: true }).selectOption('category');
  assert.equal(await button('Apply step').isDisabled(), true);
  await button('Use right column manager').click();
  assert.equal(await button('Apply step').isDisabled(), false);
  await button('Remove key 2').click();
  await page.getByLabel('Search left table columns', { exact: true }).fill('revenue');
  assert.deepEqual(await page.locator('.prep-join-columns').first().getByRole('button').allTextContents(), ['#revenue']);
  await page.getByLabel('Search left table columns', { exact: true }).fill('');
  await button('Apply step').click();
  assert.equal(await page.locator('.prep-node.staged').count(), 0);
  assert.deepEqual(await page.locator('.prep-port-label').allTextContents(), ['LEFT', 'RIGHT']);
  await button('Configure step').click();
  const edges = await page.locator('.prep-graph').evaluate(graph => {
    return [...graph.querySelectorAll('[data-to]')].filter(edge => edge.dataset.to !== 'output').map(edge => {
      const parent = edge.dataset.from === 'input' ? graph.querySelector('.input-node') : graph.querySelector(`[data-step-id="${edge.dataset.from}"] > .prep-node`);
      const box = parent.getBoundingClientRect(), line = edge.getBoundingClientRect();
      return { from: edge.dataset.from, offset: Math.abs(line.y - (box.y + box.height / 2)) };
    });
  });
  assert.ok(edges.every(edge => edge.offset <= 1), JSON.stringify(edges));
  await capture('prep-configure');
  geometry.push(await page.locator('.prep-workspace').evaluate(node => ({ width: node.clientWidth, scroll: node.scrollWidth, font: getComputedStyle(node).fontFamily, size: getComputedStyle(node).fontSize })));
  assert.equal(geometry[0].width, geometry[0].scroll);
  assert.match(geometry[0].font, /Arial/); assert.equal(geometry[0].size, '12px');
  assert.ok((await page.locator('.prep-join-editor button, .prep-join-editor select, .prep-join-editor input').evaluateAll(nodes => nodes.map(n => getComputedStyle(n).fontSize))).every(size => size === '12px' || size === '20px')); // Remove-key glyph is intentionally larger.
  await preview().click();
  assert.match(await page.locator('.prep-preview').innerText(), /Needs local or hosted API/);
  assert.equal(await page.locator('.prep-preview tbody tr').count(), 0);
  assert.equal(await button('Save pipeline').isDisabled(), true);
  await capture('prep-preview');
  // Saved local draft retains the actual transformation config on reload.
  await page.reload();
  const draft = await page.evaluate(() => JSON.parse(localStorage.getItem('opensight-prep-draft')));
  assert.equal(draft.opensightPrep.steps[0].config.type, 'INTEGER');
  assert.equal(draft.opensightPrep.steps[1].config.joinType, 'left');
  await page.locator('.prep-step-node').last().locator(':scope > .prep-node').click();
  await button('Configure step').click();
  await page.setViewportSize({ width: 390, height: 844 });
  await capture('prep-mobile');
  const mobile = await page.evaluate(() => ({ width: document.documentElement.clientWidth, scroll: document.documentElement.scrollWidth }));
  geometry.push(mobile); assert.ok(mobile.scroll <= mobile.width, JSON.stringify(mobile));
  await page.setViewportSize({ width: 1440, height: 1100 });
  await button('Cancel').click();
  await button('＋ Append').click();
  assert.match(await page.locator('.prep-configure').innerText(), /PREP_SCHEMA_MISMATCH/);
  assert.equal(await button('Apply step').isDisabled(), true);
  await capture('prep-append-mismatch');
  assert.deepEqual(errors, []); assert.deepEqual(external, []);
  await writeFile(resolve(out, 'verification.json'), JSON.stringify({ errors, external, geometry, passed: true }, null, 2));
  console.log(JSON.stringify({ errors, external, geometry, passed: true }));
} catch (error) {
  await page.screenshot({ path: resolve(out, 'failure.png'), fullPage: true });
  await writeFile(resolve(out, 'failure.txt'), await page.locator('.data-prep').innerText());
  throw error;
} finally { await browser.close(); }
